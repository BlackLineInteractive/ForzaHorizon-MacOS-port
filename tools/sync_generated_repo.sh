#!/usr/bin/env bash
# Copy forza-recomp/generated/ into the PRIVATE RecompiledForzaHorizon-generated checkout
# and push. The generated C++ is translated game code: it must never be committed to
# this repository. Adapted from RecompiledHaloReach's tools/sync_generated_repo.sh.
# Usage: tools/sync_generated_repo.sh [checkout-dir]   (default ~/RecompiledForzaHorizon-generated)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/RecompiledForzaHorizon-generated}"
MAIN="$(git -C "$ROOT" rev-parse --short HEAD)"
SDK="$("${REXSDK:-$HOME/rexglue-sdk-nightly/0.10.0.24/linux-amd64}/bin/rexglue" --version 2>/dev/null | head -1)"

[ -d "$DEST/.git" ] || { echo "no git checkout at $DEST" >&2; exit 1; }
[ "$(gh repo view "$(git -C "$DEST" remote get-url origin)" --json visibility -q .visibility)" = PRIVATE ] \
    || { echo "refusing: $DEST's origin is not a private repository" >&2; exit 1; }

# The private repo keeps its own README and CI workflow (.github), which are not codegen output.
rsync -a --delete --exclude .git --exclude .github --exclude README.md "$ROOT/forza-recomp/generated/" "$DEST/"
sed -i -E "s/(From manifest\/hints at RecompiledForzaHorizon commit: ).*/\1$MAIN/; s/(Generated by: ReXGlue SDK ).*/\1$SDK/" "$DEST/README.md"
cd "$DEST"
git add -A
if git diff --cached --quiet; then echo "generated code unchanged"; exit 0; fi
# SYNC_TRAILER: extra lines for the commit message (e.g. co-author lines).
git -c user.name=agent -c user.email=agent@local commit -q \
    -m "Codegen output for RecompiledForzaHorizon@$MAIN ($SDK)" ${SYNC_TRAILER:+-m "$SYNC_TRAILER"}
git push -q origin HEAD
echo "pushed generated code for $MAIN"

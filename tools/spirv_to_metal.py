#!/usr/bin/env python3
"""Rewrite the SDK's built-in Vulkan shaders as native Metal Shading Language.

The ReXGlue SDK ships its own shaders (EDRAM resolves, texture untiling, gamma, host depth
store, the presenter's output filters, ImGui) only as SPIR-V arrays in
src/{graphics,ui}/shaders/vulkan_spirv/*.h. This takes each array, translates it to MSL with
SPIRV-Cross, and checks that Apple's Metal compiler accepts the result.

Bindings: every Vulkan descriptor set becomes a Metal argument buffer at [[buffer(set)]],
with the Vulkan binding number as the member index ([[id(binding)]]), so a Metal backend can
fill them in the same layout the Vulkan backend uses. Push constants go to
[[buffer(PUSH_CONSTANT_BUFFER)]] (see --push-constant-buffer).

Usage: tools/spirv_to_metal.py [--sdk ~/rexglue-sdk-src-forza/sdk] [--out forza-recomp/metal_shaders]
                               [--metallib forza-recomp/metal_shaders/rexgpu_builtin.metallib]
"""
import argparse
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIRS = ("src/graphics/shaders/vulkan_spirv", "src/ui/shaders/vulkan_spirv")
ARRAY_RE = re.compile(r"\{([^}]*)\}\s*;", re.S)
WORD_RE = re.compile(r"0x([0-9A-Fa-f]{8})")


def extract_spirv(header_path):
    text = open(header_path).read()
    match = ARRAY_RE.search(text.split("#endif", 1)[-1])
    if not match:
        raise ValueError("no SPIR-V array")
    words = [int(w, 16) for w in WORD_RE.findall(match.group(1))]
    if not words or words[0] != 0x07230203:
        raise ValueError("not SPIR-V (bad magic)")
    return struct.pack("<%dI" % len(words), *words)


def convert(header_path, sdk, out_dir, tmp_dir, msl_version):
    name = os.path.basename(header_path)[:-2]  # fullscreen_cw_vs
    spv = os.path.join(tmp_dir, name + ".spv")
    msl = os.path.join(out_dir, name + ".metal")
    air = os.path.join(tmp_dir, name + ".air")
    manual = os.path.join(out_dir, "manual", name + ".metal")
    if os.path.exists(manual):
        # Hand-written where SPIRV-Cross cannot translate the shader.
        if os.path.exists(msl):
            os.remove(msl)
        return compile_msl(name, manual, air, msl_version)
    with open(spv, "wb") as f:
        f.write(extract_spirv(header_path))
    cross = subprocess.run(
        ["spirv-cross", spv, "--msl", "--msl-version", msl_version,
         "--msl-argument-buffers", "--msl-argument-buffer-tier", "1",
         "--msl-decoration-binding",
         "--msl-force-active-argument-buffer-resources",
         "--rename-entry-point", "main", name, vertex_or_stage(name),
         "--output", msl],
        capture_output=True, text=True)
    if cross.returncode != 0:
        return name, "spirv-cross: " + cross.stderr.strip()
    with open(msl) as f:
        source = f.read()
    with open(msl, "w") as f:
        f.write("// Generated by tools/spirv_to_metal.py from the ReXGlue SDK's %s.\n"
                "// Do not edit: rerun the tool.\n" % os.path.relpath(header_path, sdk))
        f.write(source)
    return compile_msl(name, msl, air, msl_version)


def compile_msl(name, msl, air, msl_version):
    metal = subprocess.run(
        ["xcrun", "-sdk", "macosx", "metal", "-c", "-std=" + msl_version_std(msl_version),
         "-mmacosx-version-min=13.0", "-O3", "-Wno-unused-variable", msl, "-o", air],
        capture_output=True, text=True)
    if metal.returncode != 0:
        return name, "metal: " + metal.stderr.strip()
    return name, None


def vertex_or_stage(name):
    if name.endswith("_vs"):
        return "vert"
    if name.endswith("_ps"):
        return "frag"
    if name.endswith("_cs"):
        return "comp"
    raise ValueError("unknown shader stage: " + name)


def msl_version_std(version):
    major, minor = int(version) // 10000, (int(version) // 100) % 100
    # The compiler names macOS Metal 2.x "macos-metal2.x" and Metal 3+ "metal3.x".
    return ("metal%d.%d" if major >= 3 else "macos-metal%d.%d") % (major, minor)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--sdk", default=os.path.expanduser("~/rexglue-sdk-src-forza/sdk"))
    parser.add_argument("--out", default=os.path.join(ROOT, "forza-recomp/metal_shaders"))
    parser.add_argument("--metallib", default=None,
                        help="also link every shader into this .metallib")
    parser.add_argument("--msl-version", default="30000",
                        help="MSL version as SPIRV-Cross takes it (30000 = Metal 3, macOS 13)")
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    args = parser.parse_args()

    for tool in ("spirv-cross", "xcrun"):
        if not shutil.which(tool):
            sys.exit("%s not found (brew install spirv-cross; Xcode command line tools)" % tool)

    headers = []
    for d in SHADER_DIRS:
        full = os.path.join(args.sdk, d)
        if not os.path.isdir(full):
            sys.exit("SDK shader directory not found: %s (run tools/build_rexglue_sdk.sh "
                     "--source-only)" % full)
        headers += sorted(os.path.join(full, f) for f in os.listdir(full) if f.endswith(".h"))

    os.makedirs(args.out, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        with ThreadPoolExecutor(args.jobs) as pool:
            results = list(pool.map(
                lambda h: convert(h, args.sdk, args.out, tmp, args.msl_version),
                headers))
        failed = [(n, e) for n, e in results if e]
        for name, error in failed:
            print("FAILED %s\n  %s" % (name, error.replace("\n", "\n  ")), file=sys.stderr)
        print("%d/%d shaders translated to MSL and compiled" % (len(results) - len(failed),
                                                                 len(results)))
        if failed:
            sys.exit(1)
        if args.metallib:
            airs = sorted(os.path.join(tmp, f) for f in os.listdir(tmp) if f.endswith(".air"))
            subprocess.run(["xcrun", "-sdk", "macosx", "metallib", *airs, "-o", args.metallib],
                           check=True)
            print("linked %s (%d KB)" % (args.metallib, os.path.getsize(args.metallib) // 1024))


if __name__ == "__main__":
    main()
